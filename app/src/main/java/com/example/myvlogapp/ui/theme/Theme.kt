/**
 * ライト／ダークは端末の設定に自動追従する（[isSystemInDarkTheme]）。
 *
 * MainActivityに configChanges="uiMode" が入っているためActivityは作り直されないが、
 * Configurationの更新はComposeへ伝わるので、設定を切り替えた瞬間に色だけが差し替わる。
 * 編集中のクリップや再生位置を失わずにテーマが変わるのはこのため。
 */
@Composable
fun MyVlogAppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    // typographyは渡していない。テンプレート由来のType.ktはM3の既定値を
    // そのまま書き写しただけで、上書きの意味が無かったため削除した。
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        content = content
    )
}
